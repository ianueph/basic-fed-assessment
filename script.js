const items_per_page = 6;

const getTotalPages = (length, items_per_page) => {
    return Math.ceil(length / items_per_page);
}

const getProductById = (id) => {
    return data.products.find(product => product.id === id);
};

const loadProducts = (currentPage) => {
    const productGrid = document.querySelector(".products-list__grid");
    productGrid.innerHTML = "";
    const skip = (currentPage - 1) * items_per_page;

    for (let i = skip; i <= skip + 5; i++) {
        if (i >= data.products.length) { break; }
        const product = data.products[i];

        const card = document.createElement("div");

        card.classList.add("border");
        card.classList.add("products-list__item")
        card.innerHTML = `
            <img src="./resources/images/products/${[product.name]}.jpg" alt="${[product.name]}">
            <h2> ${product.name} </h2> 
            <h3> ${product.price} ${product.currency} </h3>
            <h3> remaining: ${product["qty-remaining"]} </h3>
            <input type="number" value="1" id="${product.id}-qty-add"> 
        `;  

        const button = document.createElement("button");
        button.innerHTML = "Add to cart!";
        button.addEventListener('click', () => {
            addToCart(
                product.id,
                document.getElementById(`${product.id}-qty-add`).value
            );
            loadCart(1);
        }); 

        card.appendChild(button);
        productGrid.appendChild(card);
    }

    loadPagination(currentPage, getTotalPages(data.products.length, items_per_page), loadProducts, ".products-list__pagination");
}

const loadPagination = (currentPage, totalPages, onPageChange, paginationClass) => {
    const paginationComponent = document.querySelector(paginationClass);

    paginationComponent.innerHTML = "";

    const pages = [];

    // always show first page
    pages.push(1);

    // left dots
    if (currentPage > 3) {
        pages.push("...");
    }

    // pages around current page
    for (
        let i = Math.max(2, currentPage - 1);
        i <= Math.min(totalPages - 1, currentPage + 1);
        i++
    ) {
        pages.push(i);
    }

    // right dots
    if (currentPage < totalPages - 2) {
        pages.push("...");
    }

    // always show last page if more than 1 page
    if (totalPages > 1) {
        pages.push(totalPages);
    }

    pages.forEach(page => {

        if (page === "...") {

            const dots = document.createElement("span");
            dots.textContent = "...";

            paginationComponent.appendChild(dots);

            return;
        }

        const button = document.createElement("button");
        button.addEventListener('click', () => {
            onPageChange(page);
        })
        button.textContent = page;

        paginationComponent.appendChild(button);
    });
};

let cart = new Map();
const addToCart = (id, qty) => {
    const parsedQty = parseInt(qty);
    const current = parseInt(cart.get(id) ?? 0);

    if ((current + parsedQty) > getProductById(id)["qty-remaining"]) { return; }

    cart.set(id, current + parsedQty);

    const product = getProductById(id);
    alert(`You added ${parsedQty} of ${product.name} into your cart! \nTotal added: +${product.price*parsedQty} ${product.currency}
        `);

    console.log(cart.get(id));
};

const subtractFromCart = (id, qty) => {
    const parsedQty = parseInt(qty);
    const current = parseInt(cart.get(id) ?? 0);

    if ( parsedQty < 0 ) {return;}
    if ( parsedQty > current ) {return;}
    if ( (current - parsedQty) < 0) {return;}
    
    if ( (current - parsedQty) === 0 ) {
        cart.delete(id);
    } else {
        cart.set(id, current - parsedQty);
    }

    const product = getProductById(id);
    alert(`You removed ${parsedQty} of ${product.name} from your cart!`);

    console.log(cart.get(id));
}

const loadCart = (currentPage) => {
    const items_per_page = 4;
    const shoppingCartGrid = document.querySelector(".shopping-cart__grid");
    shoppingCartGrid.innerHTML = "";

    const items = Array.from(cart.entries()); 
    const skip = (currentPage - 1) * items_per_page;
    
    for (let i = skip; i <= skip + 3; i++) {
        if (i >= items.length) { break; }

        const [id, qty] = items[i]
        const product = getProductById(id);

        const card = document.createElement("div");

        card.classList.add("border");
        card.classList.add("shopping-cart__item")
        card.innerHTML = `
            <img src="./resources/images/products/${[product.name]}.jpg" alt="${[product.name]}">
            <h2> ${product.name} </h2> 
            <h3> ${product.price} ${product.currency} </h3>
            <h3>qty in cart: ${qty}</h3>
            <input type="number" id="${product.id}-qty-sub" value="1">
        `;  

        const button = document.createElement("button");
        button.innerHTML = "Remove from cart.";
        button.addEventListener('click', () => {
            subtractFromCart(
                product.id,
                document.getElementById(`${product.id}-qty-sub`).value
            );
            loadCart(1);
        }); 

        card.appendChild(button);
        shoppingCartGrid.appendChild(card);
    }

    loadPagination(currentPage, getTotalPages(items.length, 4), loadCart, ".shopping-cart__pagination")
}

